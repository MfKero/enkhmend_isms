def mn(s):
    if not isinstance(s, str):
        return s
    if s in EXACT:
        return EXACT[s]
    for a, b in PHRASES:
        if a in s:
            s = s.replace(a, b)
    # "1. ...2. ..." гэж наалдсан дугаарласан жагсаалтыг мөрөөр салгах
    s = re.sub(r'(?<=[.!?])\s*(?=\d{1,2}\.\s?[А-ЯӨҮЁA-Z])', '\n', s)
    # "олгох.Хэрэглэгчийн" маягийн наалдсан өгүүлбэр
    s = re.sub(r'(?<=[а-яөүё])\.(?=[А-ЯӨҮЁ])', '. ', s)
    s = s.replace('​', '')
    return s
